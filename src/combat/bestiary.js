export const bestiaryOf = (kind) => BESTIARY[kind] || null;

// Какие из встреченных видов ещё не представлены игроку.
export function unseenKinds(kinds, seen = {}) {
  return [...new Set(kinds)].filter((k) => BESTIARY[k] && !seen[k]);
}

// Строка при сдвиге врага: в какую фазу перешёл — что это значит.
export const shiftNote = (kind, phase) => {
  const b = BESTIARY[kind];
  if (!b) return '';
  return phase === 'past' ? b.toPast : b.toPresent;
};
